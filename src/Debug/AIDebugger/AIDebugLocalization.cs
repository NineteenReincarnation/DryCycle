    internal static AIDebugLanguage Language { get; set; } = AIDebugLanguage.Chinese;

    internal static string T(string key)
    {
        Dictionary<string, string> table = Language == AIDebugLanguage.Chinese ? Chinese : English;
        if (key != null && table.TryGetValue(key, out string value)) return value;
        return key ?? "?";
    }

    internal static string DecisionState(AIDebugDecisionState state) => T("state." + state.ToString().ToLowerInvariant());
    internal static string EntityState(AIDebugEntityState state) => T("entity." + state.ToString().ToLowerInvariant());
